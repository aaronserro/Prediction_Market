package com.betting.backend.user;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.MigrationVersion;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

@Testcontainers(disabledWithoutDocker = true)
class UserDeactivationMigrationIT {

    @Container
    private static final PostgreSQLContainer<?> POSTGRES =
            new PostgreSQLContainer<>("postgres:16-alpine");

    @BeforeAll
    static void migrateSchema() throws SQLException {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE users (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        username varchar(255),
                        email varchar(255),
                        password_hash varchar(255) NOT NULL
                    )
                    """);
            statement.execute("""
                    CREATE TABLE user_roles (
                        user_id bigint NOT NULL REFERENCES users(id),
                        role varchar(255)
                    )
                    """);
            statement.execute("""
                    CREATE TABLE trades (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id bigint REFERENCES users(id)
                    )
                    """);
        }

        Flyway.configure()
                .dataSource(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword())
                .baselineOnMigrate(true)
                .baselineVersion(MigrationVersion.fromVersion("0"))
                .target(MigrationVersion.fromVersion("1"))
                .load()
                .migrate();

        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            statement.executeUpdate("""
                    INSERT INTO users
                        (id, username, email, password_hash, account_enabled, token_version)
                    VALUES
                        (100, 'legacy-disabled', 'legacy@example.com', 'old-hash', false, 7)
                    """);
            statement.executeUpdate(
                    "INSERT INTO user_roles (user_id, role) VALUES (100, 'ROLE_ADMIN')");
            statement.executeUpdate("""
                    INSERT INTO admin_mfa_credentials
                        (user_id, encrypted_secret, enabled)
                    VALUES
                        (100, 'encrypted', true)
                    """);
        }

        Flyway.configure()
                .dataSource(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword())
                .target(MigrationVersion.fromVersion("2"))
                .load()
                .migrate();
    }

    @Test
    void legacyDisabledUserIsAnonymizedAndCredentialsAreRemoved() throws SQLException {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            ResultSet user = statement.executeQuery("""
                    SELECT username, email, password_hash, account_enabled, token_version,
                           deactivated_at, deactivated_by_user_id
                    FROM users WHERE id = 100
                    """);
            assertThat(user.next()).isTrue();
            assertThat(user.getString("username")).isEqualTo("deactivated-100");
            assertThat(user.getString("email")).isEqualTo("deactivated-100@users.invalid");
            assertThat(user.getString("password_hash")).isEqualTo("!deactivated!");
            assertThat(user.getBoolean("account_enabled")).isFalse();
            assertThat(user.getLong("token_version")).isEqualTo(8L);
            assertThat(user.getTimestamp("deactivated_at")).isNotNull();
            assertThat(user.getObject("deactivated_by_user_id")).isNull();

            assertThat(count(statement,
                    "SELECT count(*) FROM user_roles WHERE user_id = 100")).isZero();
            assertThat(count(statement,
                    "SELECT count(*) FROM admin_mfa_credentials WHERE user_id = 100")).isZero();
        }
    }

    @Test
    void deactivationStateConstraintRejectsInconsistentRows() throws SQLException {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            assertThatThrownBy(() -> statement.executeUpdate("""
                    INSERT INTO users
                        (username, email, password_hash, account_enabled, token_version,
                         deactivated_at)
                    VALUES
                        ('enabled-with-date', 'enabled-with-date@example.com', 'hash', true, 0,
                         CURRENT_TIMESTAMP)
                    """))
                    .isInstanceOf(SQLException.class);

            assertThatThrownBy(() -> statement.executeUpdate("""
                    INSERT INTO users
                        (username, email, password_hash, account_enabled, token_version)
                    VALUES
                        ('disabled-without-date', 'disabled-without-date@example.com', 'hash', false, 0)
                    """))
                    .isInstanceOf(SQLException.class);
        }
    }

    @Test
    void physicalDeletionIsRejectedAndRelatedRowsRemain() throws SQLException {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            statement.executeUpdate("""
                    INSERT INTO users
                        (id, username, email, password_hash, account_enabled, token_version)
                    VALUES
                        (200, 'retained-user', 'retained@example.com', 'hash', true, 0)
                    """);
            statement.executeUpdate("INSERT INTO trades (user_id) VALUES (200)");

            assertThatThrownBy(() -> statement.executeUpdate("DELETE FROM users WHERE id = 200"))
                    .isInstanceOf(SQLException.class)
                    .hasMessageContaining("Physical user deletion is prohibited");

            assertThat(count(statement, "SELECT count(*) FROM users WHERE id = 200")).isOne();
            assertThat(count(statement, "SELECT count(*) FROM trades WHERE user_id = 200")).isOne();
        }
    }

    private static Connection connection() throws SQLException {
        return DriverManager.getConnection(
                POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
    }

    private static long count(Statement statement, String sql) throws SQLException {
        try (ResultSet result = statement.executeQuery(sql)) {
            result.next();
            return result.getLong(1);
        }
    }
}